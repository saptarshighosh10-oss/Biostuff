"""Do the developability heads help EACH OTHER? (honest stacked multi-task)

Every GDPa antibody has all properties measured, and the properties are physically
correlated (aggregation / hydrophobicity / self-association / stability). This tests
whether predicting the STRONG properties from sequence and feeding those predictions in
as extra clues lifts the WEAK ones (thermostability, expression).

Honesty: the helper predictions used as features are OUT-OF-FOLD.
  - For held-out test antibodies: helpers are trained on the full training studies (clean).
  - For training antibodies: helper predictions are generated by k-fold within the train
    set, so the target model never sees an over-optimistic helper feature.
Evaluation stays leave-one-GDPa-out + strict dedup + catch-the-bad AUC, same as before.

Run:
  python -m model.head_multitask_honest --out results/head_multitask_honest.json
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path
from statistics import mean

from model.head_b_gbm import build_feature_vector
from model.head_b_acsins_charge import charge_features
from model.head_b_catch_rate import _bad_labels, _metrics, BAD_FRACTION
from model.head_developability_honest import _load_rows, _seqkey, _tuned_lgbm

HELPERS = ["self_association", "hydrophobicity", "polyreactivity", "aggregation"]
TARGETS = ["thermostability", "expression"]


def _oof_and_test_preds(train_rows, test_rows, feat, n_splits=5, seed=42):
    """Return (oof_pred_by_id_for_train, pred_by_id_for_test) for one property's rows."""
    from sklearn.model_selection import KFold
    import numpy as np
    X = [feat(r) for r in train_rows]
    y = [float(r["endpoint_value"]) for r in train_rows]
    oof = {}
    if len(train_rows) >= 30:
        kf = KFold(n_splits=min(n_splits, len(train_rows)), shuffle=True, random_state=seed)
        for tr, te in kf.split(X):
            m = _tuned_lgbm(); m.fit([X[i] for i in tr], [y[i] for i in tr])
            for pos, i in zip(m.predict([X[i] for i in te]), te):
                oof[id(train_rows[i])] = float(pos)
    # full model for test predictions
    test_pred = {}
    if test_rows:
        full = _tuned_lgbm(); full.fit(X, y)
        test_pred = {id(r): float(p) for r, p in zip(test_rows, full.predict([feat(r) for r in test_rows]))}
    return oof, test_pred


def run(use_plm: bool = True, frac: float = BAD_FRACTION) -> dict:
    rows = _load_rows()
    feat_cache: dict[str, list[float]] = {}

    def base_feat(r):
        s = _seqkey(r)
        v = feat_cache.get(s)
        if v is None:
            v = build_feature_vector(r, use_plm=use_plm) + charge_features(r)
            feat_cache[s] = v
        return v

    by_family = defaultdict(list)
    for r in rows:
        by_family[str(r.get("assay_family"))].append(r)
    studies = sorted({str(r.get("study_id")) for r in rows})

    def eval_target(target_family, with_helpers):
        evals = []
        trows_all = by_family.get(target_family, [])
        for held in studies:
            test = [r for r in trows_all if str(r.get("study_id")) == held]
            held_seqs = {_seqkey(r) for r in test}
            train = [r for r in trows_all if str(r.get("study_id")) != held and _seqkey(r) not in held_seqs]
            if len(train) < 40 or len(test) < 20:
                continue

            helper_train_oof = {}   # family -> {seqkey -> pred}
            helper_test = {}
            if with_helpers:
                for hf in HELPERS:
                    if hf == target_family:
                        continue
                    h_all = by_family.get(hf, [])
                    h_train = [r for r in h_all if str(r.get("study_id")) != held and _seqkey(r) not in held_seqs]
                    h_test = [r for r in h_all if str(r.get("study_id")) == held]
                    if len(h_train) < 40:
                        continue
                    oof, tpred = _oof_and_test_preds(h_train, h_test, base_feat)
                    # map by sequence (an antibody may recur across assays)
                    helper_train_oof[hf] = {_seqkey(r): oof[id(r)] for r in h_train if id(r) in oof}
                    helper_test[hf] = {_seqkey(r): tpred[id(r)] for r in h_test}

            def feat(r):
                v = list(base_feat(r))
                if with_helpers:
                    sk = _seqkey(r)
                    is_test = str(r.get("study_id")) == held
                    for hf in HELPERS:
                        if hf == target_family or hf not in helper_train_oof:
                            continue
                        src = helper_test[hf] if is_test else helper_train_oof[hf]
                        v.append(src.get(sk, 0.0))  # 0 = neutral when that antibody has no helper measurement
                return v

            m = _tuned_lgbm()
            m.fit([feat(r) for r in train], [float(r["endpoint_value"]) for r in train])
            preds = {id(r): float(p) for r, p in zip(test, m.predict([feat(r) for r in test]))}
            by_assay = defaultdict(list)
            for r in test:
                by_assay[str(r.get("assay_metric"))].append(r)
            for metric, arows in by_assay.items():
                if len(arows) < 20:
                    continue
                direction = str(arows[0].get("endpoint_direction") or "higher_bad")
                vals = [float(r["endpoint_value"]) for r in arows]
                scores = [preds[id(r)] if direction == "higher_bad" else -preds[id(r)] for r in arows]
                mm = _metrics(_bad_labels(vals, direction, frac), scores, frac)
                if mm:
                    evals.append(mm)
        aucs = [e["auc"] for e in evals]
        return round(mean(aucs), 3) if aucs else None, len(evals)

    out = {}
    for tf in TARGETS:
        solo, n1 = eval_target(tf, with_helpers=False)
        multi, n2 = eval_target(tf, with_helpers=True)
        out[tf] = {"solo_auc": solo, "multitask_auc": multi,
                   "delta": round((multi or 0) - (solo or 0), 3), "n_tests": n2}
    return {"head": "developability_multitask_honest",
            "helpers": HELPERS, "features": "biophysical+charge+plm", "targets": out}


if __name__ == "__main__":
    p = argparse.ArgumentParser(description="Honest stacked multi-task: do heads help each other?")
    p.add_argument("--no-plm", action="store_true")
    p.add_argument("--out", default="results/head_multitask_honest.json")
    args = p.parse_args()
    rep = run(use_plm=not args.no_plm)
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(json.dumps(rep, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print("Do the heads help each other? (honest leave-one-GDPa-out AUC)\n")
    print(f"  {'target':<18}{'solo':>8}{'+helpers':>10}{'delta':>8}")
    for tf, v in rep["targets"].items():
        print(f"  {tf:<18}{str(v['solo_auc']):>8}{str(v['multitask_auc']):>10}{v['delta']:>+8}")
    print(f"\nwrote {args.out}")